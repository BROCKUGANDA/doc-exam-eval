"""Regenerate the results tables in README.md from benchmark/results/results.json.

`--regrade` re-scores every stored transcript and writes the tables between the
RESULTS:AUTOGEN markers here, so the figures the README asserts are the figures the code
computes. Hand-transcribed results are the easiest kind of claim to let go stale.

Everything outside the markers is prose and is left exactly as found. The prose quotes numbers
too; those are checked against results.json by scripts/check_readme_claims.py rather than
regenerated, because a sentence is not a table.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
README = REPO / "README.md"
RESULTS = REPO / "benchmark" / "results" / "results.json"

START = "<!-- RESULTS:AUTOGEN start -->"
END = "<!-- RESULTS:AUTOGEN end -->"

#: Display names for the dimension table, in the order the rubric discusses them.
DIMENSION_LABELS = {
    "recall": "recall (did they find it)",
    "precision": "precision (no fabrication)",
    "rule_mapping": "rule mapping",
    "evidence": "evidence traceability",
    "severity": "severity classification",
    "uncertainty": "uncertainty escalation",
    "format": "output format",
}


def _model_rows(models: dict) -> list[str]:
    ranked = sorted(
        (spec for spec, m in models.items() if m["trials_scored"]),
        key=lambda spec: -(models[spec]["overall_mean_total"] or 0),
    )
    lines = [
        "| Model | Scored trials | Mean /100 | pass@k tasks | pass^k tasks | "
        "Critical false clearances | Mean latency |",
        "|---|---|---|---|---|---|---|",
    ]
    for rank, spec in enumerate(ranked):
        m = models[spec]
        covered = m["tasks_covered"]
        latency = f"{m['mean_latency_s']}s" if m["mean_latency_s"] is not None else "—"
        mean = m["overall_mean_total"] or 0
        mark = "**" if rank == 0 else ""
        lines.append(
            f"| `{spec}` | {m['trials_scored']} | {mark}{mean:.2f}{mark} | "
            f"{m['tasks_passed_at_k']}/{covered} | {m['tasks_passed_hat_k']}/{covered} | "
            f"{m['critical_false_clearances']} | {latency} |"
        )
    return lines


def _dimension_rows(credit: dict[str, float]) -> list[str]:
    lines = ["| Dimension | Mean credit |", "|---|---|"]
    for name, pct in sorted(credit.items(), key=lambda kv: kv[1]):
        label = DIMENSION_LABELS.get(name, name)
        bold = "**" if name in ("recall", "uncertainty") else ""
        lines.append(f"| {bold}{label}{bold} | {bold}{pct}%{bold} |")
    return lines


def _dimension_rows(credit) -> list[str]:
    lines = ["| Dimension | Mean credit |", "|---|---|"]
    rows = [(str(k), v) for k, v in (credit.items() if isinstance(credit, dict) else credit)]
    if isinstance(credit, dict):
        rows.sort(key=lambda kv: kv[1])
    for name, pct in rows:
        label = DIMENSION_LABELS.get(name, name)
        bold = "**" if name in ("recall", "uncertainty") else ""
        lines.append(f"| {bold}{label}{bold} | {bold}{pct}%{bold} |")
    return lines


def _pairs(rows) -> list[tuple[str, int]]:
    """Accept the aggregator's ranked pairs, or re-rank an unranked dict.

    Anything that reaches here through results.json has already lost insertion order to
    ``sort_keys=True``, so a dict is sorted by count here rather than trusted. Reading
    alphabetical order as a ranking put "AMOUNT_EXCEEDS_CREDIT" at the top of the
    most-missed table once; the claim looked plausible and was wrong.
    """
    items = [tuple(r) for r in rows] if isinstance(rows, list) else list(rows.items())
    pairs = [(str(k), int(v)) for k, v in items]
    if isinstance(rows, dict):
        pairs.sort(key=lambda kv: (-kv[1], kv[0]))
    return pairs


def _missed_rows(missed) -> list[str]:
    lines = ["| Most-missed code | Trials |", "|---|---|"]
    lines += [f"| `{code}` | {n} |" for code, n in _pairs(missed)[:6]]
    return lines


def build_tables(blob: dict) -> list[str]:
    pw = blob["panel_wide"]
    panel = blob["panel"]
    lines = [
        START,
        f"Panel `{panel['panel_id']}`, temperature {panel['temperature']}, "
        f"{panel['trials_per_task']} trials per task per model. These four tables are "
        "regenerated by `python scripts/write_readme_tables.py`; the prose around them is not.",
        "",
        "### Models with scored trials",
        "",
        *_model_rows(blob["models"]),
        "",
        f"**{pw['trials_scored']} scored trials, {pw['trials_passed']} passed "
        f"({pw['pass_rate_pct']}%), mean {pw['mean_total']}/100.**",
        "",
        "### Mean credit by dimension, across all scored trials",
        "",
        "Credit is the mean of each dimension's ratio, so 100% means the models earned every "
        "point that dimension offers. Sorted worst first.",
        "",
        *_dimension_rows(pw["dimension_credit_pct"]),
        "",
        "### Most-missed findings across the whole panel",
        "",
        *_missed_rows(pw["missed_code_counts"]),
        "",
        "### Hard caps fired",
        "",
        "| Cap | Trials |",
        "|---|---|",
    ]
    lines += [f"| `{cap}` | {n} |" for cap, n in _pairs(pw["cap_counts"])]
    lines.append(END)
    return lines


def _replace_between(text: str, start: str, end: str, body: list[str]) -> str:
    lo = text.find(start)
    hi = text.find(end)
    if lo == -1 or hi == -1 or hi < lo:
        raise SystemExit(f"README.md is missing the {start!r} / {end!r} markers")
    return text[:lo] + "\n".join(body) + text[hi + len(end):]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if README.md is not what the data says (for CI)")
    args = ap.parse_args(argv)

    if not RESULTS.is_file():
        print("no results.json; run `python run_eval.py --regrade` first")
        return 2
    blob = json.loads(RESULTS.read_text(encoding="utf-8"))
    if "panel_wide" not in blob:
        print("results.json predates panel_wide; re-run `python run_eval.py --regrade`")
        return 2

    original = README.read_text(encoding="utf-8")
    updated = _replace_between(original, START, END, build_tables(blob))
    if args.check:
        if updated != original:
            print("README.md result tables are stale; run scripts/write_readme_tables.py",
                  file=sys.stderr)
            return 1
        print("README.md result tables match results.json")
        return 0
    README.write_text(updated, encoding="utf-8", newline="\n")
    print(f"rewrote the results block in {README.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
