"""Reporting helpers that keep expert review cheap and, more importantly, recorded.

The Human-expertise criterion is worth 10 points and the guide says judges look for signs
that no expert checked the work. A claim of review is worth nothing; a dated per-rule and
per-finding sign-off sheet, generated from the same artefacts that do the grading, is
evidence. Regenerating it after any rulebook change re-opens the affected rows, so a
severity edited late cannot silently keep an old approval.
"""

from __future__ import annotations

from pathlib import Path

from benchmark.generator.build import Scenario
from benchmark.rulebook.model import Rulebook
from benchmark.truth.engine import GroundTruth

HEADER = """# DOC-EXAM expert review record

Generated by `python run_eval.py --review-sheet` against rulebook version {version}
(fingerprint `{fingerprint}`). Do not hand-edit this file: regenerate it, then fill in the
verdict columns. Regeneration re-opens any row whose rule or finding changed.

This is the record that every task, reference answer and grading rule below was reviewed by
a human examiner, as the Participant Guide requires (p.12, p.17). The engine computes these
values; the columns marked EMPTY are the places where computation cannot substitute for
professional judgment and must not.

## 1. Severity ladder — the load-bearing decision

Every finding's severity is looked up from its rule, so these verdicts decide the severity
dimension of the grade and whether the missed-critical cap fires.

| Rule | Declared severity | Codes it governs | Statement (first clause) | Examiner verdict (critical / minor / none) | Initials | Date |
|---|---|---|---|---|---|---|
{severity_rows}

## 2. Tolerance boundaries — where a correct answer could be false-failed

| Boundary | Current value | Source | Where it decides an outcome | Examiner verdict | Initials | Date |
|---|---|---|---|---|---|---|
{boundary_rows}

## 3. Per-task findings — is each one materially wrong in real examination?

The `field` and `code` columns are computed by the engine from the rendered documents. What
only an examiner can answer is whether the classification matches practice.

{task_sections}

## 4. Honest limits of this record

- Findings are computed, not asserted, so a wrong reference answer is a *rulebook* error. If
  you disagree with a severity or a tolerance above, change the rulebook, not the answer.
- Rules declared but never exercised by any task are listed below; they are untested and
  should not be described as validated.

Never exercised by any task: {unexercised}
"""

BOUNDARY_SOURCES = [
    ("Money rounding", "money_equality", "rounding to the currency's minor units decides whether 100,000.0 equals 100,000.00"),
    ("'about' amount band", "amount_tolerance", "±{about}% applies when the credit says 'about' and states no explicit tolerance"),
    ("Packaged quantity tolerance", "quantity_tolerance", "{packaged}% — any shortfall on packaged goods is a discrepancy"),
    ("Bulk quantity tolerance", "quantity_tolerance", "{bulk}% shortfall is permitted for bulk cargo"),
    ("Permitted unit conversions", "permitted_unit_conversions", "MT->KG, CASE->PCS and the rest; CTN->PCS deliberately has no default factor"),
    ("Non-working-day deadline shift", "business_calendar", "a deadline landing on a closed date moves to the next working day of the supplied calendar"),
    ("Pass threshold", "graders/scoring.py", "total >= 70 with no cap is a pass"),
]


def _fmt(template: str, rb: Rulebook) -> str:
    amount = rb.definitions["amount_tolerance"]
    qty = rb.definitions["quantity_tolerance"]
    return template.format(
        about=amount["about_pct"],
        packaged=qty["packaged"]["allowed_pct"],
        bulk=qty["bulk"]["allowed_pct"],
    )


def write_expert_review(
    cases: dict[str, tuple[object, object]],
    scenarios: dict[str, Scenario],
    rb: Rulebook,
    out_path: Path,
) -> Path:
    exercised_rules = {f.rule_id for _, truth in cases.values() for f in truth.findings}
    exercised_codes = {f.code for _, truth in cases.values() for f in truth.findings}

    severity_rows = []
    for r in rb.rules:
        if r.severity == "none":
            continue
        first_clause = str(r.statement).strip().split(". ")[0][:110]
        severity_rows.append(
            f"| {r.id} | {r.severity} | {', '.join(r.codes) or '—'} | {first_clause} |  |  |  |"
        )

    boundary_rows = []
    for label, key, detail in BOUNDARY_SOURCES:
        value = rb.definitions.get(key) if key in rb.definitions else "70 (threshold)"
        rendered = _fmt(detail, rb)
        short = str(value)
        if len(short) > 60:
            short = short[:57] + "..."
        boundary_rows.append(f"| {label} | `{short}` | rulebook:{key} | {rendered} |  |  |  |")

    task_sections: list[str] = ["## 3. Per-task findings"]
    for cid in sorted(cases):
        package, truth = cases[cid]
        scenario = scenarios[cid]
        lines = [
            f"### {cid} — {scenario.title}",
            "",
            f"Author's planted intent: {len(truth.findings)} finding(s), {len(truth.unresolved)} unestablishable field(s).",
            "",
            "| Finding | Code | Field | Rule | Severity (computed) | Documents | Observed | Material in practice? (Y/N) | Severity correct? | Initials | Date |",
            "|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        if truth.findings:
            for f in truth.findings:
                observed = "; ".join(f"{k}={v}" for k, v in list(f.observed.items())[:3])
                lines.append(
                    f"| {f.finding_id} | {f.code} | {f.field} | {f.rule_id} | {f.severity} | "
                    f"{', '.join(f.docs)} | {observed[:60]} |  |  |  |  |"
                )
        else:
            lines.append("| — | no findings: this task tests restraint |  |  |  |  |  |  |  |  |")
        if truth.unresolved:
            lines.append("")
            lines.append("Fields that cannot be established (escalation is the correct answer):")
            for u in truth.unresolved:
                lines.append(f"- `{u.field}` — {u.reason} — {u.note}")
        lines.append("")
        lines.append("**Examiner: is CLEAR / the reported set the verdict a colleague and you would both reach?**  ")
        lines.append("Signature: ______________________  Date: ____________")
        task_sections.append("\n".join(lines))

    unexercised = sorted(
        {r.id for r in rb.rules if r.id not in exercised_rules and r.severity != "none"}
    )
    never_codes = sorted(rb.codes - exercised_codes)

    content = HEADER.format(
        version=rb.version,
        fingerprint=rb.fingerprint(),
        severity_rows="\n".join(severity_rows),
        boundary_rows="\n".join(boundary_rows),
        task_sections="\n\n".join(task_sections),
        unexercised=(
            ", ".join(unexercised) + ("; codes never exercised: " + ", ".join(never_codes) if never_codes else "")
            if unexercised or never_codes
            else "none — every declared rule and code is exercised by at least one task"
        ),
    )
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding="utf-8", newline="\n")
    return out_path
